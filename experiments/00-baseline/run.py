#!/usr/bin/env python3
"""Experiment 00: the baseline. Prints results.md on standard output.

A quiet period below the gas target, a burst well above the block limit, then
quiet again, on a network of nodes running the `geth` and `eip-8141` profiles
with plain transfers and self-paying frame transactions from disjoint senders.
"""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / "ref" / "python"), str(ROOT / "sim")]

from emem import Head  # noqa: E402
from emem_sim import (ChainConfig, FrameLoad, NetworkConfig, Scenario, Simulation, TransferLoad,  # noqa: E402
                      percentile, table)

SEED = 1
NODES = 30
GAS_LIMIT = 2_100_000  # 100 plain transfers; the target is 50
QUIET, BURST = 2.5, 12.0  # transfers per second; the target is 50 / 12 = 4.2 per second
PHASES = [("quiet", 0, 600), ("burst", 600, 900), ("after", 900, 1800)]
DURATION = 1800


def main() -> None:
    plain = [f"p{i:03d}" for i in range(400)]
    framed = [f"f{i:03d}" for i in range(100)]
    scenario = Scenario(
        seed=SEED,
        nodes=NODES,
        network=NetworkConfig(degree=8, latency=(0.02, 0.10), arrive_timeout=0.5),
        chain=ChainConfig(slot_time=12, proposer="rotate", block_delay=(0.1, 1.0)),
        genesis=Head(timestamp=0, gas_limit=GAS_LIMIT, gas_used=GAS_LIMIT // 2, base_fee=1_000_000_000),
        accounts={a: 10**21 for a in plain + framed},
    )
    sim = Simulation(scenario)
    sim.add_load(TransferLoad("quiet", rate=QUIET, senders=plain, stop=PHASES[0][2]))
    sim.add_load(TransferLoad("burst", rate=BURST, senders=plain, start=PHASES[1][1], stop=PHASES[1][2]))
    sim.add_load(TransferLoad("after", rate=QUIET, senders=plain, start=PHASES[2][1]))
    sim.add_load(FrameLoad("frames", rate=0.2, senders=framed))
    rec = sim.run(DURATION)

    out = ["# 00. Baseline: results", "",
           f"Generated by `experiments/00-baseline/run.py`, seed {SEED}, {NODES} nodes, "
           f"{DURATION} simulated seconds. Do not edit by hand.", ""]

    out += ["## By phase", "",
            "Transactions are assigned to the phase in which they were submitted. Delays are in seconds "
            "from submission to the block that included them; the base fee is the next block's, in gwei, "
            "at the end of the phase; the pool is the mean number of pending transactions per node, "
            "averaged over the phase's samples, and then at the phase's end.", ""]
    rows = []
    for name, start, stop in PHASES:
        txs = [r for r in rec.txs.values() if start <= r.submitted_at < stop]
        delays = [r.included_at - r.submitted_at for r in txs if r.included_at is not None]
        samples = [s for s in rec.samples if start < s["at"] <= stop]
        blocks = [b for b in rec.blocks if start < b["at"] <= stop]
        rows.append([name, f"{start}-{stop}", len(txs), len(delays), percentile(delays, 50), percentile(delays, 90),
                     percentile(delays, 99), sum(b["gas_used"] for b in blocks) / max(1, len(blocks)) / GAS_LIMIT,
                     samples[-1]["base_fee"] / 1e9, sum(s["pending_mean"] for s in samples) / len(samples),
                     samples[-1]["pending_mean"]])
    out.append(table(["phase", "seconds", "submitted", "included", "delay p50", "delay p90", "delay p99",
                      "block fullness", "base fee", "pool", "pool at end"], rows))

    out += ["", "## Propagation", "",
            "Seconds from submission until a share of the nodes held the transaction as pending, over every "
            "transaction that reached that share.", ""]
    rows = []
    for share in (0.5, 0.9, 1.0):
        times = rec.propagation_times(NODES, share)
        rows.append([f"{int(share * 100)}%", len(times), percentile(times, 50), percentile(times, 90),
                     percentile(times, 99)])
    out.append(table(["nodes reached", "transactions", "p50", "p90", "p99"], rows))

    out += ["", "## Admission results", "",
            "Every answer any node's pool gave to any transaction, summed over nodes.", ""]
    results = Counter()
    dropped = Counter()
    for r in rec.txs.values():
        results.update(r.results)
        dropped.update(r.dropped)
    out.append(table(["result", "count"], [[k, v] for k, v in sorted(results.items())]))
    out += ["", "Removals after admission, summed over nodes (`replaced` counts the replaced transaction).", ""]
    out.append(table(["reason", "count"], [[k, v] for k, v in sorted(dropped.items())]))

    out += ["", "## The pool at the end", "",
            "Node n00's pending transactions after the last block, against the next base fee: those whose fee cap "
            "is below it, those queued behind one of those in their sender's nonce order, and the rest.", ""]
    node = sim.net.nodes["n00"]
    base_fee = sim.chain.head.next_base_fee()
    pending, _ = node.pool.content()
    under = behind = includable = 0
    stuck_senders = 0
    for txs in pending.values():
        stuck = False
        for tx in txs:
            if tx.max_fee < base_fee:
                under += 1
                stuck = True
            elif stuck:
                behind += 1
            else:
                includable += 1
        stuck_senders += stuck
    out.append(table(["next base fee", "pending", "fee cap below base fee", "behind one of those", "includable",
                      "senders stuck"],
                     [[base_fee / 1e9, under + behind + includable, under, behind, includable, stuck_senders]]))

    out += ["", "## Frame transactions", ""]
    frames = [r for r in rec.txs.values() if r.tx.type == 6]
    delays = [r.included_at - r.submitted_at for r in frames if r.included_at is not None]
    out.append(table(["submitted", "included", "delay p50", "delay p90"],
                     [[len(frames), len(delays), percentile(delays, 50), percentile(delays, 90)]]))
    print("\n".join(out))


if __name__ == "__main__":
    main()
